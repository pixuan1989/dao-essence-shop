/**
 * sync-wallpaper-data.js
 * Reads wallpapers.json and embeds the data into wallpaper-detail.html
 * as an inline <script id="wp-data"> tag so Vercel auth walls don't block fetch.
 * 
 * Run: node scripts/sync-wallpaper-data.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'wallpaper-detail.html');
const jsonPath = path.join(root, 'wallpapers.json');

const wallpapers = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
const jsonStr = JSON.stringify(wallpapers);

let html = fs.readFileSync(htmlPath, 'utf-8');

// Replace existing wp-data block or insert new one
const wpDataRegex = /<script id="wp-data" type="application\/json">[\s\S]*?<\/script>/;

if (wpDataRegex.test(html)) {
    html = html.replace(wpDataRegex, `<script id="wp-data" type="application/json">${jsonStr}</script>`);
    console.log('Updated existing wp-data block');
} else {
    // Insert before the first <script> tag after the footer
    html = html.replace(/(<\/div>\s*\n\s*<script>)/, `</div>\n\n    <!-- Embedded wallpaper data (auto-generated by sync-wallpaper-data.js) -->\n    <script id="wp-data" type="application/json">${jsonStr}</script>\n\n    $1`);
    console.log('Inserted new wp-data block');
}

fs.writeFileSync(htmlPath, html, 'utf-8');
console.log(`Synced ${wallpapers.length} wallpapers into wallpaper-detail.html`);
